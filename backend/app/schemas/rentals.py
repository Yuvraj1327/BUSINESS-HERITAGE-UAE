"""Step 10 request/response models: rental agreements, PDC cheques, renewal, rental alerts."""

import uuid
from datetime import date, datetime
from typing import Literal

from pydantic import BaseModel, Field, field_validator, model_validator

from app.schemas.finance import AuditEntry, Bank, Strict
from app.schemas.money import Money, PositiveMoneyIn

ChequeStatus = Literal["Pending", "Cleared", "Bounced"]
AgreementStatusT = Literal["Scheduled", "Active", "Expiring", "Expired", "Renewed", "Terminated"]
Timing = Literal["overdue", "due_7", "due_30", "later", "done"]

_MIN_DATE, _MAX_DATE = date(2000, 1, 1), date(2100, 12, 31)


def _blank(v: str | None) -> str | None:
    return v or None


def _sane(v: date | None) -> date | None:
    if v is not None and not (_MIN_DATE <= v <= _MAX_DATE):
        raise ValueError("Enter a realistic date (2000 to 2100)")
    return v


# ---------------------------------------------------------------- inputs
class ChequeLineIn(Strict):
    cheque_no: str = Field(min_length=1, max_length=50)
    cheque_date: date
    amount: PositiveMoneyIn
    bank: Bank

    @field_validator("cheque_date")
    @classmethod
    def _d(cls, v: date) -> date:
        return _sane(v)  # type: ignore[return-value]


class ScheduleParams(Strict):
    annual_rent: PositiveMoneyIn
    cheque_count: int = Field(ge=1, le=12)
    first_cheque_date: date
    first_cheque_no: str = Field(min_length=1, max_length=50)
    bank: Bank

    @field_validator("first_cheque_date")
    @classmethod
    def _d(cls, v: date) -> date:
        return _sane(v)  # type: ignore[return-value]


class AgreementIn(ScheduleParams):
    branch_id: uuid.UUID
    landlord: str = Field(min_length=1, max_length=150)
    unit: str | None = Field(default=None, max_length=200)
    start_date: date
    end_date: date | None = None  # default: start + 12 months - 1 day
    notes: str | None = Field(default=None, max_length=1000)
    # The reviewed schedule. Omitted -> generated by the approved formula. Provided -> validated (count, total, numbers).
    cheques: list[ChequeLineIn] | None = Field(default=None, max_length=12)

    @field_validator("unit", "notes")
    @classmethod
    def _b(cls, v: str | None) -> str | None:
        return _blank(v)

    @field_validator("start_date", "end_date")
    @classmethod
    def _dates(cls, v: date | None) -> date | None:
        return _sane(v)

    @model_validator(mode="after")
    def _order(self) -> "AgreementIn":
        if self.end_date is not None and self.end_date <= self.start_date:
            raise ValueError("The agreement end date must be after the start date")
        return self


class AgreementUpdate(Strict):
    branch_id: uuid.UUID
    landlord: str = Field(min_length=1, max_length=150)
    unit: str | None = Field(default=None, max_length=200)
    start_date: date
    end_date: date
    notes: str | None = Field(default=None, max_length=1000)
    reason: str | None = Field(
        default=None, max_length=500
    )  # required by the service for branch / date changes

    @field_validator("unit", "notes", "reason")
    @classmethod
    def _b(cls, v: str | None) -> str | None:
        return _blank(v)

    @field_validator("start_date", "end_date")
    @classmethod
    def _dates(cls, v: date) -> date:
        return _sane(v)  # type: ignore[return-value]

    @model_validator(mode="after")
    def _order(self) -> "AgreementUpdate":
        if self.end_date <= self.start_date:
            raise ValueError("The agreement end date must be after the start date")
        return self


class RenewIn(Strict):
    """Everything is optional: omitted values carry forward (rent, cheque count, bank) or are derived (dates, numbers)."""

    annual_rent: PositiveMoneyIn | None = None
    cheque_count: int | None = Field(default=None, ge=1, le=12)
    first_cheque_date: date | None = None  # default: the new agreement start date
    first_cheque_no: str | None = Field(
        default=None, min_length=1, max_length=50
    )  # default: continues the old series
    bank: Bank | None = None
    notes: str | None = Field(default=None, max_length=1000)
    cheques: list[ChequeLineIn] | None = Field(default=None, max_length=12)

    @field_validator("notes")
    @classmethod
    def _b(cls, v: str | None) -> str | None:
        return _blank(v)

    @field_validator("first_cheque_date")
    @classmethod
    def _d(cls, v: date | None) -> date | None:
        return _sane(v)


class RenewConfirmIn(RenewIn):
    expected_end_date: (
        date  # the end date the Owner saw: a stale or repeated renewal is refused (409)
    )
    confirm: bool  # must be true: renewal is an explicit, confirmed action


