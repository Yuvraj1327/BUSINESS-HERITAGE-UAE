import { apiClient } from '@/lib/api-client'
import {
  actorsSchema,
  catalogSchema,
  chartSetSchema,
  overviewSchema,
  reportSchema,
} from '@/schemas/analytics'

export type Period = 'day' | 'week' | 'month' | 'year'
export interface ReportFilters {
  date_from: string
  date_to: string
  period: Period
  branch_id?: string
  supplier_id?: string
  account?: string
  kind?: string
  module?: string
  action?: string
  actor_id?: string
  /** Activity history: 'user' = signed-in users, 'system' = setup / operator events. Omit for all. */
  source?: 'user' | 'system'
  q?: string
}
export interface ReportQuery extends ReportFilters {
  sort?: string
  desc?: boolean
  page: number
  page_size: number
}
type Params = Record<string, string | number | boolean | undefined>
const clean = (p: Params): Params =>
  Object.fromEntries(Object.entries(p).filter(([, v]) => v !== undefined && v !== ''))

export const getCatalog = async () =>
  catalogSchema.parse((await apiClient.get<unknown>('/reports/catalog')).data)
export const getOverview = async (f: ReportFilters) =>
  overviewSchema.parse(
    (await apiClient.get<unknown>('/reports/overview', { params: clean({ ...f }) })).data,
  )
export const getCharts = async (f: ReportFilters) =>
  chartSetSchema.parse(
    (await apiClient.get<unknown>('/reports/charts', { params: clean({ ...f }) })).data,
  )
export const getReport = async (key: string, q: ReportQuery) =>
  reportSchema.parse(
    (await apiClient.get<unknown>(`/reports/${key}`, { params: clean({ ...q }) })).data,
  )
export const getActors = async () =>
  actorsSchema.parse((await apiClient.get<unknown>('/reports/activity/actors')).data)

/** Export is generated by the server from the same filters; the browser only saves the returned file. */
export async function downloadExport(
  key: string,
  format: 'csv' | 'xlsx',
  f: ReportFilters & { sort?: string; desc?: boolean },
): Promise<string> {
  const res = await apiClient.get<Blob>(`/reports/${key}/export`, {
    params: clean({ ...f, format }),
    responseType: 'blob',
    timeout: 120_000,
  })
  const header = String(res.headers['content-disposition'] ?? '')
  const name = /filename="?([^";]+)"?/.exec(header)?.[1] ?? `${key}.${format}`
  const url = URL.createObjectURL(res.data)
  const a = document.createElement('a')
  a.href = url
  a.download = name
  document.body.appendChild(a)
  a.click()
  a.remove()
  URL.revokeObjectURL(url)
  return name
}
