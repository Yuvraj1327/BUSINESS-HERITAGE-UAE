import { AlertTriangle, Bell, Info } from 'lucide-react'
import { Link } from 'react-router-dom'
import { useAuth } from '@/auth/use-auth'
import { usePermissions } from '@/auth/use-permissions'
import { Button } from '@/components/ui/button'
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuLabel,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from '@/components/ui/dropdown-menu'
import { useAlertSummary } from '@/hooks/use-alerts'
import { cn } from '@/lib/utils'

/**
 * Notification bell. One central feed (GET /alerts/summary): the unread count and the most important active
 * alerts, generated by the server from the real records. Only users with the alerts grant (the Owner) request it.
 * Nothing is sent outside the app.
 */
function hasMuted(n: { critical: boolean; warning: boolean; info: boolean } | undefined) {
  return n !== undefined && !(n.critical && n.warning && n.info)
}

export function NotificationMenu() {
  const { can } = usePermissions()
  const allowed = can('alerts', 'read')
  const feed = useAlertSummary(allowed)
  // The user's notification choices (Settings > Notifications) decide which levels the bell shows.
  const muted = useAuth().profile?.preferences.notifications
  const shown = (feed.data?.recent ?? []).filter((a) => muted?.[a.severity as 'critical'] !== false)
  const filtered = shown.length !== (feed.data?.recent.length ?? 0) || hasMuted(muted)
  const unread = filtered
    ? shown.filter((a) => a.status === 'unread').length
    : (feed.data?.unread ?? 0)
  return (
    <DropdownMenu>
      <DropdownMenuTrigger asChild>
        <Button
          variant="ghost"
          size="icon"
          className="relative size-11 md:size-9"
          aria-label={unread > 0 ? `Notifications, ${unread} unread` : 'Notifications'}
        >
          <Bell aria-hidden />
          {unread > 0 ? (
            <span
              aria-hidden
              className="absolute top-1 right-1 flex min-w-4 items-center justify-center rounded-full bg-destructive px-1 text-[10px] font-semibold text-white"
            >
              {unread > 99 ? '99+' : unread}
            </span>
          ) : null}
        </Button>
      </DropdownMenuTrigger>
      <DropdownMenuContent align="end" className="w-80">
        <DropdownMenuLabel className="font-semibold">Notifications</DropdownMenuLabel>
        <DropdownMenuSeparator />
        {!allowed ||
        (feed.data && (feed.data.total_active === 0 || (filtered && shown.length === 0))) ? (
          <div className="px-4 py-6 text-center text-sm text-muted-foreground">
            You have no notifications.
          </div>
        ) : feed.isLoading ? (
          <div className="px-4 py-6 text-center text-sm text-muted-foreground">Loading…</div>
        ) : feed.error || !feed.data ? (
          <div role="alert" className="px-4 py-6 text-center text-sm text-destructive">
            Notifications could not be loaded.
          </div>
        ) : (
          <ul className="max-h-96 overflow-y-auto" aria-label="Alerts">
            {shown.map((a) => (
              <li key={a.id}>
                <Link
                  to={a.href}
                  className="flex items-start gap-2 px-3 py-2 text-sm hover:bg-accent focus-visible:bg-accent focus-visible:outline-none"
                >
                  {a.severity === 'info' ? (
                    <Info className="mt-0.5 size-4 shrink-0 text-blue-700" aria-hidden />
                  ) : (
                    <AlertTriangle
                      className={cn(
                        'mt-0.5 size-4 shrink-0',
                        a.severity === 'critical' ? 'text-destructive' : 'text-warning',
                      )}
                      aria-hidden
                    />
                  )}
                  <span>
                    <span className={cn('block', a.status === 'unread' && 'font-semibold')}>
                      {a.type_label}
                    </span>
                    <span className="block text-xs text-muted-foreground">{a.detail}</span>
                  </span>
                </Link>
              </li>
            ))}
          </ul>
        )}
        {allowed ? (
          <>
            <DropdownMenuSeparator />
            <DropdownMenuItem asChild>
              <Link to="/notifications" className="justify-center font-medium">
                View all notifications
                {feed.data && feed.data.total_active > 0 ? ` (${feed.data.total_active})` : ''}
              </Link>
            </DropdownMenuItem>
          </>
        ) : null}
      </DropdownMenuContent>
    </DropdownMenu>
  )
}
